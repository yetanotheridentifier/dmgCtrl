/**
 * Generates src/data/xwaCards.ts, the XWA pilot and ship table, from YASB's card data.
 *
 * YASB (raithos/xwing, MIT) keeps current XWA points by hand in one CoffeeScript file and has no
 * data API, so this compiles that file and runs YASB's own setup to get the same XWS ids YASB
 * exports. The commit is pinned so the table only changes when someone moves YASB_COMMIT and
 * reviews the diff. It runs YASB's code, so read the YASB diff before moving the pin: node:vm
 * keeps it off our globals but is not a security boundary.
 *
 * Usage: node scripts/generate-xwing-data.mjs
 */

import { writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'
import vm from 'vm'
import coffee from 'coffeescript'

const __dirname = dirname(fileURLToPath(import.meta.url))

export const YASB_COMMIT = 'f598bb5d12b703f2c7f4f235c5d63b9ad9d22c8c'
const SOURCE_URL = `https://raw.githubusercontent.com/raithos/xwing/${YASB_COMMIT}/coffeescripts/content/cards-common.coffee`
const OUTPUT = resolve(__dirname, '..', 'src', 'data', 'xwaCards.ts')

// xwing-data2 ship ids that other builders still export, mapped to YASB's id for the same ship.
const SHIP_ALIASES = { upsilonclassshuttle: 'upsilonclasscommandshuttle' }

const canonicalize = s => s.toLowerCase().replace(/[^a-z0-9]/g, '')

export function extractXwingData(coffeeSource) {
  const js = coffee.compile(coffeeSource, { bare: true })
  const context = vm.createContext({ exportObj: {} })
  // getXWSBaseName lives in YASB's xwing.coffee, which isn't loaded; this mirrors it.
  vm.runInContext(
    "String.prototype.getXWSBaseName = function () { return this.split('-')[0] };" +
      'var exportObj = this.exportObj;' +
      js,
    context,
  )
  const yasb = context.exportObj
  const cards = yasb.basicCardData()
  yasb.setupCommonCardData(cards)

  const pilots = {}
  for (const p of cards.pilotsById) {
    if (p.skip) continue
    const limits = [p.max_per_squad, p.restricted].filter(n => n !== undefined)
    pilots[p.xws] = {
      name: p.name,
      ship: canonicalize(p.ship),
      faction: canonicalize(p.faction),
      points: p.points,
      ...(p.loadout !== undefined && { loadout: p.loadout }),
      unique: Boolean(p.unique),
      ...(limits.length && { limit: Math.min(...limits) }),
      yasbId: p.id,
    }
  }

  const ships = {}
  for (const s of Object.values(cards.ships)) ships[canonicalize(s.name)] = s.name
  for (const [alias, id] of Object.entries(SHIP_ALIASES)) ships[alias] = ships[id]

  return { pilots, ships }
}

export function renderModule({ pilots, ships }, commit) {
  const entries = table => Object.entries(table).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  return [
    '// XWA pilots and ships keyed by XWS id.',
    `// Generated by scripts/generate-xwing-data.mjs from raithos/xwing@${commit}; do not edit manually.`,
    '',
    'export interface XwaPilot {',
    '  name: string',
    '  ship: string',
    '  faction: string',
    '  points: number',
    '  loadout?: number',
    '  unique: boolean',
    '  limit?: number',
    '  yasbId: number',
    '}',
    '',
    'export const xwaPilots: Record<string, XwaPilot> = {',
    ...entries(pilots),
    '}',
    '',
    'export const xwaShips: Record<string, string> = {',
    ...entries(ships),
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const res = await fetch(SOURCE_URL)
  if (!res.ok) throw new Error(`${SOURCE_URL} answered ${res.status}`)
  const data = extractXwingData(await res.text())
  writeFileSync(OUTPUT, renderModule(data, YASB_COMMIT))
  console.log(`Wrote ${Object.keys(data.pilots).length} pilots and ${Object.keys(data.ships).length} ships to ${OUTPUT}`)
}
