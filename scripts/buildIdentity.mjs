// Generate `src/buildIdentity.ts` for the PWA: the release and commit the build was made from.
//
// A COPY of `sealed/scripts/buildIdentity.mjs`, kept the same shape: the PWA and Sealed share no build
// code, and both are built in the same deploy run, so each carries the same release number. Change
// one and change the other.
//
// This file is GITIGNORED. A tracked identity would be issued twice by two branches and would
// conflict on every merge; an untracked file can do neither.
//
// Two identifiers, two audiences:
//   COMMIT_ID  machine-facing, git-derived, unique by construction.
//   RELEASE    human-facing, issued once by the pipeline so it cannot collide. Sent on every
//              analytics event and shown on the Help screen.
//
// In CI both come from the environment, which also sidesteps the shallow clone: `actions/checkout`
// defaults to `fetch-depth: 1`, so anything derived from history would be wrong, while `rev-parse`
// works at depth 1 and `run_number` needs no history at all.
import { writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'

const git = (...args) => {
  try {
    return execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
  } catch {
    return ''
  }
}

/**
 * A tree with uncommitted changes cannot be attributed to any commit. Marking it is what stops a
 * dirty build being read as a clean one.
 */
const isDirty = () => git('status', '--porcelain') !== ''

function identity() {
  // GitHub Actions sets both for every step, so CI needs no workflow changes.
  const sha = process.env.GITHUB_SHA
  const run = process.env.GITHUB_RUN_NUMBER
  if (sha) {
    return { commit: sha.slice(0, 7), release: run ?? `ci-${sha.slice(0, 7)}` }
  }

  const local = git('rev-parse', '--short', 'HEAD') || 'unknown'
  const commit = isDirty() ? `${local}-dirty` : local
  // No release number exists locally, and a local build must never look like one.
  return { commit, release: `dev-${local}` }
}

const { commit, release } = identity()
const path = new URL('../src/buildIdentity.ts', import.meta.url)

writeFileSync(path, `// GENERATED by scripts/buildIdentity.mjs. Not tracked.
/** Machine-facing. Git-derived and unique, so a build is attributable to real code.
 *  A \`-dirty\` suffix means the tree had uncommitted changes and the build belongs to no commit. */
export const COMMIT_ID = '${commit}'

/** Human-facing. Issued by the deployment pipeline, so it is monotonic and cannot collide.
 *  Local builds carry a \`dev-\` marker instead, because they are not releases. */
export const RELEASE = '${release}'
`)

console.log(`build identity → commit ${commit}, release ${release}`)
